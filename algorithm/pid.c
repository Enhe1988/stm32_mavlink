/**
  * @brief          pid out clear
  * @param[out]     pid: PID struct data point
  * @retval         none
  */
/**
  * @brief          pid 输出清除
  * @param[out]     pid: PID结构数据指针
  * @retval         none
  */
void PID_clear(pid_type_def *pid)
{
    if (pid == NULL)
    {
        return;
    }

    pid->error[0] = pid->error[1] = pid->error[2] = 0.0f;
    pid->Dbuf[0] = pid->Dbuf[1] = pid->Dbuf[2] = 0.0f;
    pid->out = pid->Pout = pid->Iout = pid->Dout = 0.0f;
    pid->fdb = pid->set = 0.0f;
    pid->dt_initialized = 0U;
}

/* PID 实际计算
 * P=Kp*e，I+=Ki*e*dt，D=Kd*(e-e_prev)/dt，输出再限幅。
 * 默认 Ki/Kd=0 只是初始整定值，两项代码已经实现；首次调用不计算 D 防止历史冲击。
 * 积分先生成候选值，若会进一步推动输出饱和则不接纳本次积分。
 * 旧 PID_calc 保留兼容；当前姿态串级路径明确调用这个含 dt 的版本。 */
fp32 PID_calc_dt(pid_type_def *pid, fp32 ref, fp32 set, fp32 dt)
{
    if (pid == NULL || !isfinite(ref) || !isfinite(set) || !isfinite(dt) || dt <= 0.0f) {
        return 0.0f;
    }
    float error = set - ref;
    float derivative = pid->dt_initialized ? (error - pid->error[0]) / dt : 0.0f;
    float integral = pid->Iout + pid->Ki * error * dt;
    LimitMax(integral, pid->max_iout);
    pid->Pout = pid->Kp * error;
    pid->Dout = pid->Kd * derivative;
    float candidate = pid->Pout + integral + pid->Dout;
    /* 已饱和时只允许有助于退出饱和方向的积分。 */
    if (!((candidate > pid->max_out && error > 0.0f) ||
          (candidate < -pid->max_out && error < 0.0f))) {
        pid->Iout = integral;
    }
    pid->error[0] = error;
    pid->set = set;
    pid->fdb = ref;
    pid->dt_initialized = 1U;
    pid->out = pid->Pout + pid->Iout + pid->Dout;
    LimitMax(pid->out, pid->max_out);
    return pid->out;
}
