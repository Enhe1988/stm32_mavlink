/**
 * @file    icm42688p_regs.h
 * @brief   ICM-42688-P 本工程实际使用的寄存器与位定义。
 *
 * 只保留初始化、INT1 DATA_RDY 和 14 字节传感器突发读取所需内容。
 * 地址与位定义来自 ICM-42688-P datasheet rev 1.2。
 */
#ifndef ICM42688P_REGS_H
#define ICM42688P_REGS_H

#include <stdint.h>


#define ICM42688_READ_BIT (0x80U)

/* Bank 0 */
#define ICM42688_DEVICE_CONFIG (0x11U)
#define ICM42688_DRIVE_CONFIG (0x13U)
#define ICM42688_INT_CONFIG (0x14U)
#define ICM42688_FIFO_CONFIG (0x16U)
#define ICM42688_TEMP_DATA1 (0x1DU)
#define ICM42688_INT_STATUS (0x2DU)
#define ICM42688_INTF_CONFIG0 (0x4CU)
#define ICM42688_PWR_MGMT0 (0x4EU)
#define ICM42688_GYRO_CONFIG0 (0x4FU)
#define ICM42688_ACCEL_CONFIG0 (0x50U)
#define ICM42688_GYRO_ACCEL_CONFIG0 (0x52U)
#define ICM42688_INT_CONFIG0 (0x63U)
#define ICM42688_INT_CONFIG1 (0x64U)
#define ICM42688_INT_SOURCE0 (0x65U)
#define ICM42688_WHO_AM_I (0x75U)
#define ICM42688_REG_BANK_SEL (0x76U)

/* Bank 1 */
#define ICM42688_INTF_CONFIG4 (0x7AU)
#define ICM42688_INTF_CONFIG6 (0x7CU)

#define ICM42688_BANK0 (0U)
#define ICM42688_BANK1 (1U)

#define ICM42688_DEVICE_CONFIG_SOFT_RESET (0x01U)
#define ICM42688_INT_STATUS_RESET_DONE (0x10U)
#define ICM42688_WHO_AM_I_VALUE (0x47U)

/* SPI 4-wire；INT1 为高有效、推挽、脉冲；仅路由 UI DATA_RDY。 */
#define ICM42688_DRIVE_CONFIG_SPI_SLEW_5 (0x05U)
#define ICM42688_INT_CONFIG_INT1 (0x03U)
#define ICM42688_INT_SOURCE0_UI_DRDY (0x08U)

/* 大端传感器数据，关闭 I2C 从接口；复位值中的大端位保持为 1。 */
#define ICM42688_INTF_CONFIG0_SPI_ONLY (0x33U)

#define ICM42688_INTF_CONFIG4_I3C_BUS_MODE (0x40U)
#define ICM42688_INTF_CONFIG4_SPI_4WIRE (0x02U)
#define ICM42688_INTF_CONFIG6_I3C_EN (0x10U)
#define ICM42688_INTF_CONFIG6_I3C_DDR_EN (0x02U)
#define ICM42688_INTF_CONFIG6_I3C_SDR_EN (0x01U)

/* ±2000 dps / ±16 g，均为 1 kHz；UI 滤波器带宽使用复位默认值。 */
#define ICM42688_GYRO_CONFIG0_2000DPS_1KHZ (0x06U)
#define ICM42688_ACCEL_CONFIG0_16G_1KHZ (0x06U)
#define ICM42688_GYRO_ACCEL_CONFIG0_DEFAULT (0x11U)

#define ICM42688_PWR_MGMT0_ACCEL_GYRO_LN (0x0FU)

#define ICM42688_SENSOR_DATA_BYTES (14U)
#define ICM42688_SPI_FRAME_BYTES (ICM42688_SENSOR_DATA_BYTES + 1U)


#endif /* ICM42688P_REGS_H */
