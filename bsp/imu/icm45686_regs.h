/**
 * @file    icm45686_regs.h
 * @brief   ICM-45686 本工程使用到的最小寄存器与位定义。
 *
 * 地址和位定义来自 ICM-45686 datasheet DS-000489 rev 1.1。
 */
#ifndef ICM45686_REGS_H
#define ICM45686_REGS_H

#include <stdint.h>


#define ICM45686_READ_BIT (0x80U)

/* User bank 0 direct registers. */
#define ICM45686_ACCEL_DATA_X1 (0x00U)
#define ICM45686_PWR_MGMT0 (0x10U)
#define ICM45686_INT1_CONFIG0 (0x16U)
#define ICM45686_INT1_CONFIG1 (0x17U)
#define ICM45686_INT1_CONFIG2 (0x18U)
#define ICM45686_INT1_STATUS0 (0x19U)
#define ICM45686_ACCEL_CONFIG0 (0x1BU)
#define ICM45686_GYRO_CONFIG0 (0x1CU)
#define ICM45686_FIFO_CONFIG0 (0x1DU)
#define ICM45686_INTF_CONFIG1_OVRD (0x2DU)
#define ICM45686_WHO_AM_I (0x72U)
#define ICM45686_IREG_ADDR_15_8 (0x7CU)
#define ICM45686_IREG_ADDR_7_0 (0x7DU)
#define ICM45686_IREG_DATA (0x7EU)
#define ICM45686_REG_MISC2 (0x7FU)

#define ICM45686_WHO_AM_I_VALUE (0xE9U)

#define ICM45686_REG_MISC2_SOFT_RESET (0x02U)
#define ICM45686_REG_MISC2_IREG_DONE (0x01U)
#define ICM45686_INT1_STATUS0_RESET_DONE (0x80U)

/* AP host interface: force 4-wire SPI, mode 0/3. */
#define ICM45686_INTF_CONFIG1_OVRD_4WIRE_MODE03 (0x0EU)

/* INT1: enable only UI DRDY; push-pull, pulse, active high. */
#define ICM45686_INT1_CONFIG0_DRDY (0x04U)
#define ICM45686_INT1_CONFIG2_PUSH_PULL_PULSE_HIGH (0x01U)

/* UI output: +/-16 g, +/-2000 dps, both at 800 Hz (ICM-45686 has no 1 kHz ODR). */
#define ICM45686_ACCEL_CONFIG0_16G_800HZ (0x16U)
#define ICM45686_GYRO_CONFIG0_2000DPS_800HZ (0x16U)
#define ICM45686_PWR_MGMT0_ACCEL_GYRO_LN (0x0FU)

/* IPREG_TOP1:SREG_CTRL (0xA200 + 0x67), bit1 selects big-endian sensor data. */
#define ICM45686_IREG_SREG_CTRL (0xA267U)
#define ICM45686_SREG_CTRL_BIG_ENDIAN (0x02U)

/* ACCEL XYZ (6) + GYRO XYZ (6) + TEMP (2), starting at 0x00. */
#define ICM45686_SENSOR_DATA_BYTES (14U)
#define ICM45686_SPI_FRAME_BYTES (ICM45686_SENSOR_DATA_BYTES + 1U)


#endif /* ICM45686_REGS_H */
